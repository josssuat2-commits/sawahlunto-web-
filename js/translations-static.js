  const english = new Map(pairs);
  const normalize = value => value.replace(/\s+/g, ' ').trim();
  function translate(value) {
    const key = normalize(value);
    if (key.startsWith('Salin kelas ')) return 'Copy class ' + key.slice(12);
    return english.get(key);
  }
  const bindings = [];
  function apply() {
    const en = localStorage.getItem('sawahlunto_lang_pref') === 'en';
    document.documentElement.lang = en ? 'en' : 'id';
    bindings.forEach(binding => {
      // Do not replace text or attributes subsequently owned by a dynamic renderer.
      if ([binding.id, binding.en].includes(binding.get())) binding.set(en ? binding.en : binding.id);
    });
  }
  // Register before the guide's dynamic listeners so they read the updated copy.
  document.addEventListener('sawahlunto:language', apply);
  document.addEventListener('DOMContentLoaded', () => {
    document.documentElement.normalize();
    const walker = document.createTreeWalker(document.documentElement, 4);
    for (let node; (node = walker.nextNode());) {
      if (node.parentElement.closest('script, style, code, [data-i18n], .scroll-letter-text, .open-letter-text, #inspectionDataContainer, #albumDataContainer, #mapDataContainer, #lanternDataContainer')) continue;
      const original = node.nodeValue;
      const translated = translate(original);
      if (translated === undefined) continue;
      const en = original.match(/^\s*/)[0] + translated + original.match(/\s*$/)[0];
      bindings.push({ get: () => node.nodeValue, set: value => { node.nodeValue = value; }, id: original, en });
    }
    document.querySelectorAll('[title], [aria-label], [alt], [placeholder], [data-demo], meta[name="description"]').forEach(element => {
      for (const attribute of ['title', 'aria-label', 'alt', 'placeholder', 'data-demo', 'content']) {
        const original = element.getAttribute(attribute);
        if (!original || (attribute === 'content' && element.tagName !== 'META')) continue;
        if (element.hasAttribute('data-i18n-' + attribute)) continue;
        const translated = translate(original);
        if (translated === undefined) continue;
        bindings.push({ get: () => element.getAttribute(attribute), set: value => element.setAttribute(attribute, value), id: original, en: translated });
      }
    });
    apply();
  });
